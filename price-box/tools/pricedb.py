#!/usr/bin/env python3
"""DinhoReviews price database tool. Run with: python3 -I tools/pricedb.py <command>

Tables (CSV, in data/):
  products.csv      one row per exact model/configuration (the id is used by articles and charts)
  retailers.csv     one row per store (kind: official | major | aggregator)
  observations.csv  append-only log: one row per price we read (date, product, retailer, price, quality, url, source)
data/prices.json is GENERATED by `build` for the website widgets. Never edit it by hand.

Commands:
  build                       regenerate data/prices.json and data/report.md
  add --date D --product P --retailer R --price N [--seller S --seller-kind third_party --in-stock yes|no|unknown
      --condition new --quality page|owner|snippet|tracker --url U --source FILE --note TEXT]
  find TEXT                   search products
  show PRODUCT_ID             list observations of a product
  stale [DAYS]                products whose newest usable price is older than DAYS (default 7)
  snippet PRODUCT_ID          print the article block (static fallback) for a product
  validate                    integrity checks (exit 1 on problems)
Quality: page = read on the live store page; owner = supplied by the owner; snippet = search snippet or
unverified listing; tracker = third-party tracker. Only page and owner feed the website.
"""
import argparse, csv, datetime as dt, html, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.normpath(os.path.join(HERE, "..", "data"))
PROD, RET, OBS = (os.path.join(DATA, f) for f in ("products.csv", "retailers.csv", "observations.csv"))
OUT, REPORT = os.path.join(DATA, "prices.json"), os.path.join(DATA, "report.md")

CFG = {"window_days": 14, "official_tolerance": 0.05, "retailer_tolerance": 0.03}
PROD_F = ["product_id", "brand", "name", "config", "model_code", "category", "value", "value_price", "value_date", "notes"]
RET_F = ["retailer_id", "name", "display", "kind", "domain"]
OBS_F = ["date", "product_id", "retailer_id", "seller", "seller_kind", "price", "in_stock", "condition", "quality", "url", "source", "note"]
QUALITY = {"page", "owner", "snippet", "tracker"}
USABLE = {"page", "owner"}
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def rd(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def wr(path, fields, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def fmt(v):
    return "${:,.0f}".format(v) if abs(v - round(v)) < 0.005 else "${:,.2f}".format(v)


def fdate(iso):
    y, m, d = iso.split("-")
    return f"{int(d)} {MONTHS[int(m)-1]} {y}"


def usable(o):
    try:
        return (o["quality"] in USABLE and o["condition"] in ("new", "") and o["in_stock"] != "no"
                and float(o["price"]) > 0)
    except ValueError:
        return False


def latest_as_of(obs, d, window):
    """latest usable observation per (retailer, seller) on or before d and within the window"""
    lo = dt.date.fromisoformat(d) - dt.timedelta(days=window)
    best = {}
    for o in obs:
        od = dt.date.fromisoformat(o["date"])
        if od > dt.date.fromisoformat(d) or od < lo:
            continue
        k = (o["retailer_id"], o["seller"])
        if k not in best or o["date"] >= best[k]["date"]:
            best[k] = o
    return list(best.values())


def pick_main(cands, ret):
    """official store if within tolerance of the lowest, else a store within a smaller tolerance, else the lowest"""
    price = lambda o: float(o["price"])
    low = min(cands, key=price)
    stores = [o for o in cands if o["seller_kind"] != "third_party"]
    if not stores:
        return low
    lp = price(low)
    off = [o for o in stores if ret[o["retailer_id"]]["kind"] == "official"]
    if off:
        c = min(off, key=price)
        if price(c) <= lp * (1 + CFG["official_tolerance"]):
            return c
    c = min(stores, key=price)
    if price(c) <= lp * (1 + CFG["retailer_tolerance"]):
        return c
    return low


def label(o, ret):
    r = ret[o["retailer_id"]]
    if o["seller_kind"] == "third_party":
        return (o["seller"] or r["name"] + " marketplace seller")
    return r["display"] or r["name"]


def build():
    prods = {p["product_id"]: p for p in rd(PROD)}
    ret = {r["retailer_id"]: r for r in rd(RET)}
    obs = rd(OBS)
    out, rep = {}, {"nourl": [], "unusable": [], "rejudge": [], "stale": []}
    by = {}
    for o in obs:
        by.setdefault(o["product_id"], []).append(o)
    today = dt.date.today()
    for pid, p in sorted(prods.items()):
        u = sorted([o for o in by.get(pid, []) if usable(o)], key=lambda o: o["date"])
        if not u:
            rep["unusable"].append(pid)
            continue
        ref = u[-1]["date"]
        cands = latest_as_of(u, ref, CFG["window_days"])
        main = pick_main(cands, ret)
        hist = []
        for d in sorted({o["date"] for o in u}):
            c = latest_as_of(u, d, CFG["window_days"])
            if not c:
                continue
            price = float(pick_main(c, ret)["price"])
            if not hist or hist[-1][1] != price:
                hist.append([d, price])
        item = {"name": p["name"], "brand": p["brand"], "category": p["category"],
                "price": float(main["price"]), "checked": ref, "seller": label(main, ret),
                "history": hist}
        if main["url"]:
            item["url"] = main["url"]
        else:
            rep["nourl"].append(f"{pid} (main: {label(main, ret)})")
        others = []
        for o in sorted(cands, key=lambda x: float(x["price"])):
            if o is main:
                continue
            e = {"seller": label(o, ret), "price": float(o["price"])}
            if o["url"]:
                e["url"] = o["url"]
            if o["seller_kind"] == "third_party":
                e["thirdParty"] = True
            others.append(e)
        if others:
            item["others"] = others
        if p["value"]:
            try:
                vp = float(p["value_price"])
                if abs(item["price"] - vp) / vp <= 0.03:
                    item["value"] = p["value"]
                else:
                    rep["rejudge"].append(f"{pid}: value '{p['value']}' was judged at {fmt(vp)}, price is now {fmt(item['price'])}")
            except ValueError:
                pass
        age = (today - dt.date.fromisoformat(ref)).days
        if age > 7:
            rep["stale"].append(f"{pid}: {age} days (checked {ref})")
        out[pid] = item
    newest = max((i["checked"] for i in out.values()), default="")
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({"updated": newest, "currency": "USD", "region": "US", "products": out}, f, indent=1, ensure_ascii=False)
        f.write("\n")
    lines = [f"# Price database report (generated {today.isoformat()})", "",
             f"Products: {len(prods)} · with a usable price: {len(out)} · observations: {len(obs)}", ""]
    for title, key in (("No usable price (only snippets, out of stock or no data)", "unusable"),
                       ("Main retailer without a product URL (box cannot link)", "nourl"),
                       ("Value verdict needs re-judging", "rejudge"),
                       ("Older than 7 days", "stale")):
        lines += [f"## {title} ({len(rep[key])})"] + [f"- {x}" for x in rep[key]] + [""]
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"built {len(out)} products; no-url {len(rep['nourl'])}, unusable {len(rep['unusable'])}, "
          f"rejudge {len(rep['rejudge'])}, stale {len(rep['stale'])}")


def validate():
    bad = []
    prods = {p["product_id"] for p in rd(PROD)}
    ret = {r["retailer_id"] for r in rd(RET)}
    seen = set()
    for i, o in enumerate(rd(OBS), 2):
        w = f"observations.csv line {i}"
        if o["product_id"] not in prods: bad.append(f"{w}: unknown product {o['product_id']}")
        if o["retailer_id"] not in ret: bad.append(f"{w}: unknown retailer {o['retailer_id']}")
        try:
            if dt.date.fromisoformat(o["date"]) > dt.date.today(): bad.append(f"{w}: date in the future")
        except ValueError: bad.append(f"{w}: bad date")
        try:
            if float(o["price"]) <= 0: bad.append(f"{w}: price must be positive")
        except ValueError: bad.append(f"{w}: bad price")
        if o["quality"] not in QUALITY: bad.append(f"{w}: bad quality {o['quality']}")
        if o["seller_kind"] not in ("retailer", "third_party"): bad.append(f"{w}: bad seller_kind")
        if o["in_stock"] not in ("yes", "no", "unknown"): bad.append(f"{w}: bad in_stock")
        if o["url"] and not o["url"].startswith("https://"): bad.append(f"{w}: url must be https")
        k = (o["date"], o["product_id"], o["retailer_id"], o["seller"])
        if k in seen: bad.append(f"{w}: duplicate of the same day, product, retailer and seller")
        seen.add(k)
    for p in rd(PROD):
        if p["value"] and p["value"] not in ("strong", "good", "fair", "weak"): bad.append(f"product {p['product_id']}: bad value")
        if p["value"] and not (p["value_price"] and p["value_date"]): bad.append(f"product {p['product_id']}: value needs value_price and value_date")
    for r in rd(RET):
        if r["kind"] not in ("official", "major", "aggregator"): bad.append(f"retailer {r['retailer_id']}: bad kind")
    print("\n".join(bad) if bad else "ok")
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build"); sub.add_parser("validate")
    a = sub.add_parser("add")
    for f, kw in (("--date", {"required": True}), ("--product", {"required": True}), ("--retailer", {"required": True}),
                  ("--price", {"required": True, "type": float}), ("--seller", {"default": ""}),
                  ("--seller-kind", {"default": "retailer", "choices": ["retailer", "third_party"]}),
                  ("--in-stock", {"default": "yes", "choices": ["yes", "no", "unknown"]}),
                  ("--condition", {"default": "new"}), ("--quality", {"default": "page", "choices": sorted(QUALITY)}),
                  ("--url", {"default": ""}), ("--source", {"default": ""}), ("--note", {"default": ""})):
        a.add_argument(f, **kw)
    f_ = sub.add_parser("find"); f_.add_argument("text")
    s = sub.add_parser("show"); s.add_argument("product")
    st = sub.add_parser("stale"); st.add_argument("days", nargs="?", type=int, default=7)
    sn = sub.add_parser("snippet"); sn.add_argument("product")
    args = ap.parse_args()

    if args.cmd == "build": build()
    elif args.cmd == "validate": sys.exit(validate())
    elif args.cmd == "add":
        row = {"date": args.date, "product_id": args.product, "retailer_id": args.retailer, "seller": args.seller,
               "seller_kind": args.seller_kind, "price": f"{args.price:g}" if args.price == round(args.price, 2) else str(args.price),
               "in_stock": args.in_stock, "condition": args.condition, "quality": args.quality, "url": args.url,
               "source": args.source, "note": args.note}
        rows = rd(OBS) + [row]
        wr(OBS, OBS_F, rows)
        if validate():
            wr(OBS, OBS_F, rows[:-1]); print("not saved"); sys.exit(1)
        print("added; run build to refresh prices.json")
    elif args.cmd == "find":
        j = json.load(open(OUT, encoding="utf-8"))["products"]
        for p in rd(PROD):
            if args.text.lower() in (p["product_id"] + " " + p["name"] + " " + p["brand"] + " " + p["model_code"]).lower():
                c = j.get(p["product_id"])
                print(p["product_id"], "|", p["name"], "|", (f"{fmt(c['price'])} at {c['seller']} ({c['checked']})" if c else "no usable price"))
    elif args.cmd == "show":
        for o in sorted(rd(OBS), key=lambda o: o["date"]):
            if o["product_id"] == args.product:
                print(o["date"], o["retailer_id"], o["seller"] or "-", fmt(float(o["price"])), o["in_stock"], o["quality"], o["source"], o["note"])
    elif args.cmd == "stale":
        j = json.load(open(OUT, encoding="utf-8"))["products"]
        for pid, c in j.items():
            age = (dt.date.today() - dt.date.fromisoformat(c["checked"])).days
            if age > args.days: print(f"{pid}\t{age} days\t{c['checked']}")
    elif args.cmd == "snippet":
        c = json.load(open(OUT, encoding="utf-8"))["products"][args.product]
        price = fmt(c["price"])
        a_ = f'<a href="{html.escape(c["url"], quote=True)}">{html.escape(c["seller"])}</a>' if c.get("url") else html.escape(c["seller"])
        pa = f'<a href="{html.escape(c["url"], quote=True)}">{price}</a>' if c.get("url") else price
        print('<!-- wp:html -->\n<div class="dr-highlight dr-highlight--price dinho-price" data-model="%s"><p class="dr-highlight__title">Price check · %s</p><p>%s: %s %s, checked %s.</p></div>\n<script src="https://dinho321.github.io/dinho-price-tracker/price-box/widget/price-box.js" defer></script>\n<!-- /wp:html -->'
              % (args.product, fdate(c["checked"]), html.escape(c["name"]), a_, pa, fdate(c["checked"])))


if __name__ == "__main__":
    main()
